"""Паузы между сообщениями-частями ответа — общие для платформ (Telegram, API)."""

# 1.5 секунды + 1 секунда на каждые 250 символов: абзац (~300 симв.) ≈ 2.7 с,
# длинные части (1600+ симв.) — потолок в 8 с.
_CHARS_PER_SECOND = 250.0
_MIN_DELAY = 1.5
_MAX_DELAY = 8.0


def send_delay(text: str) -> float:
    """Пауза перед отправкой сообщения поверх предыдущего: имитация набора —
    чем длиннее сообщение, тем дольше пауза. От 1.5 до 8 секунд."""
    return min(_MAX_DELAY, max(_MIN_DELAY, 1.5 + len(text or "") / _CHARS_PER_SECOND))
