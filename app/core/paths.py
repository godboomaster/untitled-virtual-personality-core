"""Путь к директории данных ядра.

Десятки мест в коде используют относительный путь "data/..." — он зависит
от текущей рабочей папки процесса. data_dir() даёт единую точку: по
умолчанию "data" (как раньше), а VPC_DATA_DIR в .env позволяет отдельному
проекту-аддону (например, Арродесу) указать свою папку данных или общую
с ядром.
"""

import os
from pathlib import Path


def data_dir() -> Path:
    return Path(os.getenv("VPC_DATA_DIR", "data"))
