"""
Основа слова («кутузовой» → «кутузов») — ОДНА на проект.

Модуль на голой стандартной библиотеке (никаких httpx/openai и т.п.): его
импортирует app.features.browser_actions, который обязан подниматься без
тяжёлых зависимостей — его запускает scripts/chrome_debug.sh (ручной запуск
браузера, когда бот сломан). web_search._WORD_ENDINGS/_stem — алиасы на
WORD_ENDINGS/stem отсюда, чтобы существующие потребители (scenario_manager,
computer_control, browser_history и сам web_search) не заметили разницы.
"""

from typing import Tuple

# Падежные окончания для матчинга в резолве сайтов: «кутузовой» (запрос) и
# «КУТУЗОВА» (заголовок страницы) должны совпадать. Срезаем окончание,
# оставляя основу ≥ 4 символов — короче даёт слишком шумные совпадения.
WORD_ENDINGS: Tuple[str, ...] = (
    "ого", "его", "ому", "ему", "ыми", "ими", "ами", "ями",
    "ая", "яя", "ое", "ее", "ой", "ей", "ый", "ий", "ых", "их",
    "ом", "ем", "ам", "ям", "ах", "ях", "ов", "ев", "ью",
    "а", "я", "у", "ю", "о", "е", "ы", "и", "ь", "s",
)


def stem(word: str) -> str:
    """Срез падежного окончания («кутузовой» → «кутузов»)."""
    for e in WORD_ENDINGS:
        if word.endswith(e) and len(word) - len(e) >= 4:
            return word[:-len(e)]
    return word
