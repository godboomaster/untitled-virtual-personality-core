"""
Сервисы: внешние источники событий (Gmail, Google Диск и Документы, GitHub,
Telegram-аккаунт пользователя, почта по IMAP, RSS, входящий вебхук) и
уведомления о них от персоны.

Поток события:

    источник (sources/*) → hub.ingest → лента (feed) → разбор (triage)
        → уведомитель (notifier) → чат персоны (веб, телефон, Telegram)

- источники только читают: ничего не отправляют, не помечают прочитанным и
  не удаляют в чужих сервисах;
- разбор решает уровень события: urgent (сразу, даже в тихие часы), notify
  (сразу или после тихих часов), digest (в сводку по расписанию), ignore
  (только в ленте). Порядок: правила пользователя → признаки источника
  (письмо из «Промоакций», чат без звука, подписка на GitHub) → модель.
  Модель по умолчанию локальная (Ollama): письма и переписка не уходят с
  компьютера; без неё работают правила и признаки;
- уведомитель склеивает пачки, держит тихие часы и «не беспокоить»,
  ограничивает частоту и шлёт сводки;
- работает один процесс на папку данных (hub.lock): два ядра на одних
  данных не дублируют уведомления и не делят сессию Telegram.

Хранится в data/integrations/: settings.json (настройки и правила),
secrets.json (токены, права 0600; наружу API их не отдаёт), state.json
(курсоры источников), feed.json (лента последних событий).
"""
