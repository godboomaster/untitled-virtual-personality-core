export const lang: 'ru' | 'en' = navigator.language.toLowerCase().startsWith('ru') ? 'ru' : 'en';
const dict: Dict = lang === 'ru' ? ru : en;

export type TextKey = keyof Dict;

export function t(key: TextKey, vars?: Record<string, string | number>): string {
  let s = dict[key];
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

/** «2 ч 14 мин», «5 мин», «12 с» */
export function duration(sec: number): string {
  const h = Math.floor(sec / 3600);
  const m = Math.floor((sec % 3600) / 60);
  if (h > 0) return `${h} ${dict.h} ${m} ${dict.m}`;
  if (m > 0) return `${m} ${dict.m}`;
  return `${Math.max(0, Math.floor(sec))} ${dict.s}`;
}
