"""Smoke-тест защиты книжных ответов: срезка маркеров [ФN] и починка обрывов.

Воспроизводит инцидент из веб-чата (api_arrodes): вопрос по лору трижды
погибал в пост-обработке —
  1) ответ, обрезанный посреди маркера «…[Ф1», признавался мусором по
     балансу скобок и подменялся заглушкой;
  2) _strip_fact_markers удалял строки с номерами вне 1..frag_count ЦЕЛИКОМ,
     и ответ вырождался в одну «ритуальную» фразу без маркера.

Проверяет: _repair_truncated_markers (хвостовые обрывы), _strip_fact_markers
(валидные / near-miss / дикие номера, коллапс-гард, frag_count=0).

Запуск: python -m scripts.test_fact_markers_guard
"""

import sys
import tempfile
import os
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))


def main():
    os.environ["DATA_DIR"] = tempfile.mkdtemp(prefix="factmarkers_smoke_")
    import importlib
    import app.core.config as config_mod
    importlib.reload(config_mod)

    ok = 0

    def check(name, cond):
        nonlocal ok
        print(f"  [{'OK' if cond else 'FAIL'}] {name}")
        ok = ok + 1 if cond else ok - 100

    from app.bot_instance import BotInstance

    strip = lambda text, frag: BotInstance._strip_fact_markers(None, text, frag)
    repair = BotInstance._repair_truncated_markers
    balanced = lambda t: t.count("[") == t.count("]")

    # ── 1. Починка обрезанного маркера ──
    check("обрыв «[Ф1» на хвосте срезается",
          repair("Кровавый Адмирал Сенор пал от руки Спэрроу. [Ф1")
          == "Кровавый Адмирал Сенор пал от руки Спэрроу.")
    check("обрыв составного маркера «[Ф22, Ф2» срезается",
          repair("Он выследил его на охоте [Ф22, Ф2".rstrip())
          == "Он выследил его на охоте")
    check("обрыв «[Ф» без номера срезается",
          repair("Тело стало марионеткой [Ф") == "Тело стало марионеткой")
    check("валидный закрытый маркер не трогается",
          repair("Строка с фактом [Ф2].") == "Строка с фактом [Ф2].")
    check("текст без скобок не меняется",
          repair("Обычный ответ без маркеров.") == "Обычный ответ без маркеров.")
    check("после починки скобки сбалансированы",
          balanced(repair("Длинный ответ с фактом [Ф1] и ещё одним [Ф2]. И обрыв [Ф3")))

    # ── 2. Срезка: валидные и near-miss маркеры ──
    out = strip("Сенор пал от руки Спэрроу во время охоты [Ф1]. "
                "Охота заняла неделю после Кирхайса [Ф2].", 3)
    check("валидные маркеры срезаны, строки сохранены",
          "Сенор пал от руки Спэрроу во время охоты." in out
          and "Охота заняла неделю после Кирхайса." in out and "Ф" not in out)
    out = strip("Спэрроу обратил его в Призрака Сенора [Ф6].", 5)
    check("near-miss номер (6 при 5 фрагментах) — строка сохранена",
          "Спэрроу обратил его в Призрака Сенора." in out)
    out = strip("Составной [Ф2, Ф3] и диапазон [Ф5-6] маркеры срезаются.", 6)
    check("составные и диапазонные маркеры обрабатываются",
          "Ф" not in out and "Составной и диапазон маркеры срезаются." in out)

    # ── 3. Дикие номера — строки удаляются (анти-выдумка) ──
    # Валидная строка заведомо содержательная (>60 букв): иначе сработал бы
    # коллапс-гард из п.4 — он не должен позволять удалению опустошать ответ.
    out = strip("Спэрроу провёл пиратскую охоту и выследил флагман Сенора в открытом море [Ф1].\n"
                "Выдуманная деталь [Ф29].", 5)
    check("дикий номер (29 при 5) — строка удалена, валидная сохранена",
          "Спэрроу провёл пиратскую охоту" in out and "Выдуманная деталь" not in out)
    out = strip("После смерти Сенора Спэрроу обратил его тело в марионетку для своих дел [Ф1].\n"
                "Ноль — тоже дикий номер [Ф0].", 5)
    check("номер 0 в смешанном ответе — строка удалена",
          "обратил его тело в марионетку" in out and "Ноль" not in out)
    out = strip("Единственная строка с диким номером [Ф40].", 5)
    check("одиночная дикая строка не удаляется (иначе ответ опустеет)",
          "Единственная строка с диким номером." in out)

    # ── 4. Коллапс-гард: воспроизведение инцидента ──
    incident = (
        "Кровавый Адмирал Сенор пал от руки Германа Спэрроу во время пиратской охоты [Ф9].\n"
        "Спэрроу выследил его и убил через неделю после расправы над Душегубом Кирхайсом [Ф10].\n"
        "Тело Сенора он превратил в марионетку — Призрака Сенора [Ф11].\n"
        "Вы хорошо отдохнули сегодня? (´• ω •`)"
    )
    out = strip(incident, 5)
    check("коллапс-гард: ответ не выродился в один ритуальный вопрос",
          "Сенор пал от руки Германа Спэрроу" in out
          and "Призрака Сенора" in out and "отдохнули" in out)
    check("коллапс-гард: маркеры из отката срезаны", "Ф" not in out)

    # Частичный случай: дикие строки удаляются, валидные остаются — отката нет
    mixed = ("Правдивый факт о Спэрроу, подтверждённый фрагментом [Ф1].\n"
             "Выдумка с диким номером [Ф40].\n"
             "Ещё правдивая строка [Ф2].")
    out = strip(mixed, 5)
    check("без коллапса дикие строки по-прежнему удаляются",
          "Правдивый факт о Спэрроу" in out and "Выдумка" not in out)

    # ── 5. frag_count=0 (поиска не было) — только срезка маркеров ──
    out = strip("Честное признание в неведении с мимикрией [Ф3].", 0)
    check("frag_count=0: маркер срезан, строка сохранена",
          "Честное признание в неведении с мимикрией." in out)

    if ok > 0:
        print("\nВсе проверки пройдены")
        return 0
    print("\nЕсть падения")
    return 1


if __name__ == "__main__":
    sys.exit(main())
