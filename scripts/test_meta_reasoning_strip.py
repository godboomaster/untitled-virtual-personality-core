"""Smoke-тест чистки мета-рассуждений: вставки **...** против утечек *...*.

Воспроизводит инцидент из веб-чата: паттерн «\\*\\s*Вероятность[^*]+\\*» в
_strip_meta_reasoning писался под одиночные звёздочки, а модель по
инструкции connor.yaml («ВНУТРЕННИЕ ПРОЦЕССЫ») обрамляет внутренние
процессы двойными. Регекс матчился посередине пары ** — съедал текст
целиком, оставляя висящий «**»:
  вход : ** Вероятность, что обычная вода окажется …: 94%. **
  выход: **

Проверяет: _strip_meta_reasoning (вставки **…** сохраняются, одиночные
*…* и голые утечки срезаются, code-блоки не повреждаются) и
_strip_markdown (соседние жирные фрагменты не склеиваются, пустые
маркеры и осиротевшая линия «**» удаляются).

Запуск: python -m scripts.test_meta_reasoning_strip
"""

import sys
import tempfile
import os
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))


def main():
    os.environ["DATA_DIR"] = tempfile.mkdtemp(prefix="metastrip_smoke_")
    import importlib
    import app.core.config as config_mod
    importlib.reload(config_mod)

    ok = 0

    def check(name, cond):
        nonlocal ok
        print(f"  [{'OK' if cond else 'FAIL'}] {name}")
        ok = ok + 1 if cond else ok - 100

    from app.bot_instance import BotInstance

    strip = BotInstance._strip_meta_reasoning
    md = BotInstance._strip_markdown
    # Астериск-релевантная часть цепочки _clean_response
    clean = lambda t: md(strip(t))

    # ── 1. Инцидент: вставка в двойных звёздочках сохраняется ──
    incident = (
        "Беру с полки бутылку воды и задерживаю взгляд на ней на секунду.\n\n"
        "Для прогулки оптимально взять 0,5–0,75 л обычной воды.\n\n"
        "Если планируешь несколько часов на улице, разумнее взять 0,75–1 л воды.\n\n"
        "** Вероятность, что обычная вода окажется наиболее универсальным выбором: 94%. **\n\n"
        "Мне нужно уточнить одну деталь: прогулка будет с активной ходьбой или в основном спокойной?"
    )
    out = clean(incident)
    check("инцидент: текст вставки «Вероятность…» не съеден",
          "Вероятность, что обычная вода окажется наиболее универсальным выбором: 94%." in out)
    check("инцидент: без висящих ** (пара маркеров цела)",
          out.count("**") == 2)
    check("инцидент: остальной ответ не тронут",
          "Беру с полки бутылку воды" in out and "Мне нужно уточнить" in out)

    # ── 2. Одиночные звёздочки и голые утечки по-прежнему срезаются ──
    check("одиночная «* Вероятность … *» срезается",
          strip("* Вероятность девиации в данном паттерне: 34%. *") == "")
    check("одиночный «* Запрос на … *» срезается",
          "Запрос на" not in strip("Ответ. * Запрос на всякий случай *"))
    out = clean("Вероятность: 87%\nОбычный ответ.")
    check("голая утечка «Вероятность: 87%» срезается, ответ остаётся",
          "87%" not in out and "Обычный ответ." in out)

    # ── 3. Художественные вставки Коннора (примеры из connor.yaml) ──
    out = clean("Он замер, не поднимая глаз.\n\n"
                "**Аномалия. Запрос не соответствует контексту предыдущих сообщений.**")
    check("вставка «**Аномалия…**» сохраняется целиком",
          "**Аномалия. Запрос не соответствует контексту предыдущих сообщений.**" in out)

    # ── 4. _strip_markdown: соседние жирные не склеиваются ──
    out = md("Взять **воду** и **зонт**.")
    check("«**воду** и **зонт**» не склеиваются в «**водузонт**»",
          out == "Взять **воду** и **зонт**.")
    check("пустой маркер «**\\n\\n**» удаляется",
          "**" not in md("Абзац.\n\n**\n\n**\n\nЕщё."))
    check("осиротевшая линия «**» удаляется",
          "**" not in md("Текст.\n**\nЕщё."))
    check("линия «***» (горизонтальная линия) удаляется",
          "***" not in md("Текст.\n***\nЕщё."))

    # ── 5. Code-блоки с звёздочками внутри не повреждаются ──
    code = "Смотри пример:\n```\n**bold in code** и *italic*\n```\nПонял?"
    check("code-блок с «**» внутри проходит чистку без изменений",
          clean(code) == code)

    if ok > 0:
        print("\nВсе проверки пройдены")
        return 0
    print("\nЕсть падения")
    return 1


if __name__ == "__main__":
    sys.exit(main())
